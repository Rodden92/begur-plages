export type Language = 'fr' | 'en' | 'es' | 'ca'
const STORAGE_KEY = 'begur_language'
const locales: Record<Language, string> = { fr: 'fr-FR', en: 'en-GB', es: 'es-ES', ca: 'ca-ES' }
function detectLanguage(): Language {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'fr' || saved === 'en' || saved === 'es' || saved === 'ca') return saved
    for (const candidate of navigator.languages ?? [navigator.language]) {
      const code = candidate.toLowerCase().split('-')[0]
      if (code === 'fr' || code === 'en' || code === 'es' || code === 'ca') return code
    }
  } catch { /* browser storage unavailable */ }
  return 'en'
}
