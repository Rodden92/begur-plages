type LanguageContextValue = { language: Language; setLanguage: (language: Language) => void; locale: string; t: (key: string) => string }
const LanguageContext = createContext<LanguageContextValue | null>(null)
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(detectLanguage)
  useEffect(() => {
    document.documentElement.lang = language
    try { localStorage.setItem(STORAGE_KEY, language) } catch { /* storage disabled */ }
  }, [language])
  const t = (key: string): string => language === 'fr' ? key : translations[language][key] ?? key
  return <LanguageContext.Provider value={{ language, setLanguage, locale: locales[language], t }}>{children}</LanguageContext.Provider>
}
export function useLanguage(): LanguageContextValue {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('LanguageProvider is missing')
  return context
}
